<#
.SYNOPSIS
  Generates forward_gen.h - linker forwarder pragmas for a proxy DLL.

.DESCRIPTION
  Enumerates all named exports of a system DLL (dumpbin required, run from
  a "x64 Native Tools Command Prompt" or via build.ps1) and emits
  #pragma comment(linker, "/EXPORT:name=realName.name,@ord") lines so a
  proxy DLL can forward every export to the renamed original.

  The generated file is committed to src\ so the project builds without
  dumpbin; regenerate it only when targeting a different system DLL or
  after a Windows update changes the export table.

.EXAMPLE
  powershell -ExecutionPolicy Bypass -File tools\gen_forwards.ps1 -Target winmm -RealName winmm_real
#>
param(
    [string] $Target   = "winmm",
    [string] $RealName = "winmm_real",
    [string] $OutFile  = (Join-Path $PSScriptRoot "..\src\forward_gen.h")
)

$src = Join-Path $env:SystemRoot "System32\$Target.dll"
if (!(Test-Path $src)) { throw "system DLL not found: $src" }

$lines = & dumpbin /exports $src
if (-not $lines) { throw "dumpbin not found or returned nothing - run from a Developer prompt" }

# Functions the proxy implements itself (none for winmm; kept for reuse):
$skip = @()

$hdr = @(
    "/* AUTO-GENERATED by tools/gen_forwards.ps1",
    " * $Target -> $RealName forwarders. Do not edit by hand. */"
)
$count = 0
foreach ($l in $lines) {
    if ($l -match '^\s+(\d+)\s+[0-9A-Fa-f]+\s+[0-9A-Fa-f]+\s+(\S+)\s*$') {
        $ord  = $Matches[1]
        $name = $Matches[2]
        if ($skip -contains $name) { continue }
        $hdr += "#pragma comment(linker, `"/EXPORT:$name=$RealName.$name,@$ord`")"
        $count++
    }
}

Set-Content -Path $OutFile -Value ($hdr -join [Environment]::NewLine) -Encoding ASCII
"forwarders=$count -> $OutFile"
